"""Generates docs/frontend-api-mapping.md: every contract endpoint (docs/backend-api-contract.md)
mapped to the Laravel route, controller action and enforced middleware, plus backend additions.

    python scripts/generate-frontend-api-mapping.py
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
contract = (ROOT / 'docs' / 'backend-api-contract.md').read_text(encoding='utf-8')
# Only the generated endpoint reference, not the implementation notes (which list additions).
contract = contract.split('<!-- endpoints:start -->', 1)[1].split('<!-- endpoints:end -->', 1)[0]

PAYLOADS = {
    'Authentication': 'auth.md', 'Account & profile (self)': 'users.md', 'Verification (KYC & aviator)': 'users.md',
    'Catalogue, content & support': 'products.md', 'Favourites & profiles': 'profiles.md',
    'Listings (seller) & media': 'listings.md', 'Offers': 'offers.md', 'Swaps': 'swaps.md',
    'Cart, checkout & orders': 'orders.md', 'Payments': 'payments.md', 'Wallet & payouts': 'transactions.md',
    'Reviews': 'reviews.md', 'Messaging': 'messages.md', 'Notifications': 'notifications.md', 'Disputes': 'disputes.md',
}

section = None
contract_eps = []
for line in contract.split('\n'):
    if line.startswith('### '):
        section = line[4:].strip()
    m = re.match(r'\| `(GET|POST|PUT|PATCH|DELETE)` \| `([^`]+)` \| ([^|]*)\|', line)
    if m:
        contract_eps.append((section, m.group(1), m.group(2), m.group(3).strip()))

raw = subprocess.run('php artisan route:list --json --path=api/v1 -v', cwd=ROOT, capture_output=True, text=True, shell=True).stdout
routes = {}
for r in json.loads(raw):
    for method in r['method'].split('|'):
        if method == 'HEAD':
            continue
        path = '/' + r['uri'][len('api/v1/'):]
        routes[(method, re.sub(r'\{[^}]+\}', '{}', path))] = (path, r)


def norm(p):
    return re.sub(r'\{[^}]+\}', '{}', p)


def enforced(r):
    mw = r['middleware']
    parts = []
    if any(m.startswith('Illuminate\\Auth\\Middleware\\Authenticate') for m in mw):
        parts.append('auth')
    elif any('OptionalAuthentication' in m for m in mw):
        parts.append('optional auth')
    else:
        parts.append('public')
    if any('EnsureStaff' in m for m in mw):
        parts.append('staff')
    for m in mw:
        if 'RequirePermission:' in m:
            parts.append('perm `' + m.split(':', 1)[1] + '`')
    if any('IdempotentRequest' in m for m in mw):
        parts.append('idempotent')
    throttles = [m.split(':', 1)[1] for m in mw if 'ThrottleRequests:' in m and not m.endswith(':api')]
    if throttles:
        parts.append('throttle `' + ','.join(throttles) + '`')
    return ' · '.join(parts)


def action(r):
    return '`' + r['action'].replace('App\\Http\\Controllers\\Api\\V1\\', '').replace('\\', '/') + '`'


# The seller listing actions share one constrained route.
ACTION_ROUTE = ('POST', '/listings/{}/{}')

out = []
w = out.append
w('# Frontend ↔ API mapping')
w('')
w('Every endpoint the Vue SPA calls (from [`backend-api-contract.md`](backend-api-contract.md)), mapped to the Laravel route, '
  'controller action and the middleware that **actually enforces** access. Generated by '
  '`python scripts/generate-frontend-api-mapping.py` from `php artisan route:list`; regenerate after route changes.')
w('')
w('- Base URL: `{VITE_API_BASE_URL}` = `https://api.pilotwardrobe.com/api/v1`. All paths below are relative to it.')
w('- **auth** = Sanctum (session cookie or bearer token) and `EnsureAccountUsable` (suspended accounts and revoked sessions are rejected). '
  '**staff** = admin or super-admin. **perm** = the effective permission must be held (`a|b` any of, `a,b` all of). '
  '**idempotent** = honours the `Idempotency-Key` header (replays return the original response). Every `/api/v1` route also has the global `api` throttle (120/min).')
w('- Ownership (my order, my listing…) is enforced inside the action, which returns **404** for records the caller cannot see.')
w('- Request/response bodies: [`api-payloads/`](api-payloads/README.md). Field-level comparison: [`payload-compatibility-audit.md`](payload-compatibility-audit.md).')
w('')

counts = {'matched': 0}
current = None
for sec, method, path, guard in contract_eps:
    if sec != current:
        current = sec
        payload = PAYLOADS.get(sec, 'admin.md' if sec and sec.startswith('Admin') else None)
        w(f'## {sec}')
        w('')
        if payload:
            w(f'Payloads: [`api-payloads/{payload}`](api-payloads/{payload})')
            w('')
        w('| Method | Path | Contract guard | Laravel action | Enforced |')
        w('|---|---|---|---|---|')
    key = (method, norm(path))
    hit = routes.get(key)
    if hit is None and method == 'POST' and re.match(r'^/listings/\{[^}]+\}/(pause|resume|archive|mark-sold|mark-unavailable|relist|resubmit)$', path):
        hit = routes.get(ACTION_ROUTE)
    if hit is None:
        w(f'| `{method}` | `{path}` | {guard} | **not implemented** | — |')
        continue
    counts['matched'] += 1
    w(f'| `{method}` | `{path}` | {guard} | {action(hit[1])} | {enforced(hit[1])} |')
w('')

contract_keys = {(m, norm(p)) for _, m, p, _ in contract_eps} | {ACTION_ROUTE}
extra = sorted((v[0], k[0], v[1]) for k, v in routes.items() if k not in contract_keys)
w('## Backend additions (not in the original contract)')
w('')
w('These are documented in [`backend-api-contract.md`](backend-api-contract.md#backend-additions) and safe for the SPA to ignore until it needs them.')
w('')
w('| Method | Path | Laravel action | Enforced |')
w('|---|---|---|---|')
for path, method, r in extra:
    w(f'| `{method}` | `{path}` | {action(r)} | {enforced(r)} |')
w('')
w(f'**Coverage:** {counts["matched"]} of {len(contract_eps)} contract endpoints implemented; {len(extra)} additions; '
  f'{len(routes)} `/api/v1` operations in total.')
w('')
w('Outside `/api/v1`: `GET /health` (load-balancer health check), `GET /sanctum/csrf-cookie`, `GET /api/documentation` and `GET /openapi` (OpenAPI), `GET /horizon` (queue dashboard, staff only).')

(ROOT / 'docs' / 'frontend-api-mapping.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('wrote docs/frontend-api-mapping.md', counts, 'extras', len(extra))
