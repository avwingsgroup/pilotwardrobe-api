<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;
use ReflectionClass;

/**
 * Regenerates the `@property` PHPDoc block of every model from the database schema and the
 * model's casts, so static analysis and IDEs see real types (Carbon, enums, arrays, string ids).
 * Run after schema changes: `php artisan dev:model-docs` (requires a migrated database).
 */
final class GenerateModelPropertyDocs extends Command
{
    protected $signature = 'dev:model-docs';

    protected $description = 'Regenerate @property docblocks on app/Models from the schema and casts.';

    private const MARK_START = '/* @properties-start (generated by dev:model-docs) */';

    public function handle(): int
    {
        foreach (File::files(app_path('Models')) as $file) {
            $class = 'App\\Models\\'.$file->getFilenameWithoutExtension();
            if (! class_exists($class) || ! is_subclass_of($class, Model::class) || (new ReflectionClass($class))->isAbstract()) {
                continue;
            }

            /** @var Model $model */
            $model = new $class;
            if (! Schema::hasTable($model->getTable())) {
                continue;
            }

            $casts = $model->getCasts();
            foreach ($model->getDates() as $dateColumn) {
                $casts[$dateColumn] ??= 'datetime';
            }
            if (method_exists($model, 'getDeletedAtColumn')) {
                $casts[$model->getDeletedAtColumn()] ??= 'datetime';
            }
            $lines = [];
            foreach (Schema::getColumns($model->getTable()) as $column) {
                $name = $column['name'];
                if ($name === 'search_vector') {
                    continue;
                }
                $type = $this->typeFor($column, $casts[$name] ?? null);
                $lines[] = " * @property {$type} \${$name}";
            }

            $this->writeBlock($file->getPathname(), $file->getFilenameWithoutExtension(), $lines);
            $this->line("documented {$class}");
        }

        return self::SUCCESS;
    }

    private function typeFor(array $column, ?string $cast): string
    {
        $nullable = $column['nullable'] ? '|null' : '';
        $base = match (true) {
            $cast === null => $this->dbType($column['type_name']),
            enum_exists($cast) => '\\'.ltrim($cast, '\\'),
            in_array($cast, ['datetime', 'date', 'immutable_datetime', 'timestamp'], true) => '\\Illuminate\\Support\\Carbon',
            in_array($cast, ['array', 'json', 'encrypted:array'], true) => 'array',
            in_array($cast, ['boolean', 'bool'], true) => 'bool',
            in_array($cast, ['integer', 'int'], true) => 'int',
            in_array($cast, ['float', 'double', 'decimal'], true) || str_starts_with($cast, 'decimal') => 'float',
            default => 'string', // hashed, encrypted, string
        };

        return $base.$nullable;
    }

    private function dbType(string $type): string
    {
        return match (true) {
            in_array($type, ['int2', 'int4', 'int8', 'integer', 'bigint', 'smallint'], true) => 'int',
            in_array($type, ['bool', 'boolean'], true) => 'bool',
            in_array($type, ['numeric', 'float4', 'float8'], true) => 'string',
            in_array($type, ['timestamp', 'timestamptz', 'date'], true) => 'string',
            default => 'string',
        };
    }

    /** @param list<string> $lines */
    private function writeBlock(string $path, string $class, array $lines): void
    {
        $src = (string) file_get_contents($path);
        $block = self::MARK_START."\n/**\n".implode("\n", $lines)."\n */\n/* @properties-end */\n";

        // Replace a previous generated block, if any.
        $src = preg_replace('#/\* @properties-start.*?/\* @properties-end \*/\n#s', '', $src) ?? $src;

        $src = preg_replace('/^((?:final )?class '.$class.' extends)/m', $block.'$1', $src, 1) ?? $src;
        file_put_contents($path, $src);
    }
}
