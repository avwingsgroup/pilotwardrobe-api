 * @property string|null $phone
 * @property string|null $password
 * @property UserRole $role
 * @property UserStatus $status
 * @property string|null $staff_role_id
 * @property string|null $country_code
 * @property string $currency
 * @property string $locale
 * @property string|null $bio
 * @property string|null $avatar_media_id
 * @property string|null $cover_media_id
 * @property string $seller_type
 * @property string|null $job_title
 * @property string|null $aircraft_type
 * @property string|null $city
 * @property string|null $state
 * @property string|null $dispatch_time
 * @property int|null $response_rate
 * @property string|null $response_time
 * @property float $rating_avg
 * @property int $reviews_count
 * @property int $sales_count
 * @property int $followers_count
 * @property array $rating_breakdown
 * @property Carbon|null $email_verified_at
 * @property string|null $two_factor_secret
 * @property array|null $two_factor_recovery_codes
 * @property Carbon|null $two_factor_confirmed_at
 * @property Carbon|null $password_changed_at
 * @property int $permissions_version
 * @property Carbon|null $last_login_at
 * @property string $signup_method
 * @property bool $marketing_opt_in
