 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 */
/* @properties-end */
class User extends Authenticatable
{
    /** @use HasFactory<UserFactory> */
    use HasApiTokens, HasFactory, HasPrefixedId, Notifiable, SoftDeletes;

    protected static string $idPrefix = 'usr';

    protected $fillable = [
        'first_name', 'last_name', 'username', 'email', 'phone', 'password', 'country_code', 'currency', 'locale',
        'bio', 'avatar_media_id', 'cover_media_id', 'seller_type', 'job_title', 'aircraft_type', 'city', 'state',
        'dispatch_time', 'signup_method', 'marketing_opt_in', 'terms_accepted_at',
    ];

    protected $hidden = ['password', 'remember_token', 'two_factor_secret', 'two_factor_recovery_codes'];

    protected $attributes = [
        'role' => 'user',
        'status' => 'active',
        'currency' => 'USD',
        'locale' => 'en',
        'seller_type' => 'individual',
    ];

    protected function casts(): array
    {
        return [
            'role' => UserRole::class,
            'status' => UserStatus::class,
            'email_verified_at' => 'datetime',
            'two_factor_confirmed_at' => 'datetime',
            'password_changed_at' => 'datetime',
            'last_login_at' => 'datetime',
            'terms_accepted_at' => 'datetime',
            'suspended_at' => 'datetime',
            'deactivated_at' => 'datetime',
            'password' => 'hashed',
            'two_factor_secret' => 'encrypted',
            'two_factor_recovery_codes' => 'encrypted:array',
            'limits' => 'array',
            'rating_breakdown' => 'array',
            'rating_avg' => 'float',
            'marketing_opt_in' => 'boolean',
        ];
    }

    // ---------------------------------------------------------------- relations

    /** @return BelongsTo<StaffRole, $this> */
    public function staffRole(): BelongsTo
    {
        return $this->belongsTo(StaffRole::class);
    }

    /** @return HasMany<UserPermissionOverride, $this> */
    public function permissionOverrides(): HasMany
    {
        return $this->hasMany(UserPermissionOverride::class);
    }

    /** @return BelongsTo<Media, $this> */
    public function avatar(): BelongsTo
    {
        return $this->belongsTo(Media::class, 'avatar_media_id');
    }

    /** @return BelongsTo<Media, $this> */
    public function cover(): BelongsTo
    {
        return $this->belongsTo(Media::class, 'cover_media_id');
    }

    /** @return HasMany<SocialAccount, $this> */
    public function socialAccounts(): HasMany
    {
        return $this->hasMany(SocialAccount::class);
    }

    /** @return HasOne<KycVerification, $this> */
    public function kyc(): HasOne
    {
        return $this->hasOne(KycVerification::class);
    }

    /** @return HasOne<AviatorCredential, $this> */
    public function aviatorCredential(): HasOne
    {
        return $this->hasOne(AviatorCredential::class);
    }

    /** @return HasMany<Listing, $this> */
    public function listings(): HasMany
    {
        return $this->hasMany(Listing::class, 'seller_id');
    }

    /** @return HasMany<Address, $this> */
    public function addresses(): HasMany
    {
        return $this->hasMany(Address::class);
    }

    /** @return HasMany<FitKitProfile, $this> */
    public function fitKitProfiles(): HasMany
    {
        return $this->hasMany(FitKitProfile::class);
    }

    /** @return HasMany<Wallet, $this> */
    public function wallets(): HasMany
    {
        return $this->hasMany(Wallet::class);
    }

    /** @return HasMany<AuthSession, $this> */
    public function authSessions(): HasMany
    {
        return $this->hasMany(AuthSession::class);
    }

    /** @return HasMany<DeviceToken, $this> */
    public function deviceTokens(): HasMany
    {
        return $this->hasMany(DeviceToken::class);
    }

    /** @return HasMany<NotificationPreference, $this> */
    public function notificationPreferences(): HasMany
    {
        return $this->hasMany(NotificationPreference::class);
    }

    /** @return HasMany<UserNote, $this> */
    public function notes(): HasMany
    {
        return $this->hasMany(UserNote::class);
    }

    // ---------------------------------------------------------------- authorisation

    /** Effective permission list (role defaults + staff bundle + grants − revocations). */
    public function permissions(): array
    {
        return app(PermissionResolver::class)->for($this);
    }

    public function hasPermission(string $permission): bool
    {
        return in_array($permission, $this->permissions(), true);
    }

    public function isStaff(): bool
    {
        return $this->role->isStaff();
    }

    public function isSuperAdmin(): bool
    {
        return $this->role === UserRole::SuperAdmin;
    }

    // ---------------------------------------------------------------- state helpers

    public function displayName(): string
    {
        return trim($this->first_name.' '.$this->last_name);
    }

    public function initials(): string
    {
        $first = mb_substr($this->first_name, 0, 1);
        $last = mb_substr($this->last_name, 0, 1);

        return mb_strtoupper($first.($last !== '' ? $last : mb_substr($this->first_name, 1, 1)));
    }

    /** "Kunle T." — the short name shown to counterparties. */
    public function shortName(): string
    {
        $last = mb_substr($this->last_name, 0, 1);

        return $last === '' ? $this->first_name : $this->first_name.' '.mb_strtoupper($last).'.';
    }

    public function hasVerifiedEmail(): bool
    {
        return $this->email_verified_at !== null;
    }

    public function kycStatus(): KycStatus
    {
        return $this->kyc->status ?? KycStatus::NotStarted;
    }

    public function isKycApproved(): bool
    {
        return $this->kycStatus() === KycStatus::Approved;
    }

    public function isAviator(): bool
    {
        return $this->role === UserRole::Aviator;
    }

    public function hasTwoFactorEnabled(): bool
    {
        return $this->two_factor_secret !== null && $this->two_factor_confirmed_at !== null;
    }

    public function isOfficialStore(): bool
    {
        return $this->seller_type === 'official_store';
    }

    public function locationLabel(): ?string
    {
        $parts = array_filter([$this->city, $this->country_code ? (locale_get_display_region('-'.$this->country_code, 'en') ?: $this->country_code) : null]);

        return $parts ? implode(', ', $parts) : null;
    }

    /** Effective account limits (AD4). Stored overrides on top of defaults. */
    public function limits(): array
    {
        return array_merge([
            'can_list' => true,
            'can_receive_payouts' => true,
            'can_trade' => true,
            'instant_payouts' => false,
            'daily_payout_limit' => 500000,
        ], $this->limits ?? []);
    }

    public function canTrade(): bool
    {
        return $this->status === UserStatus::Active && $this->limits()['can_trade'];
    }

    public function canList(): bool
    {
        return $this->status === UserStatus::Active && $this->limits()['can_list'];
    }

    public function bumpPermissionsVersion(): void
    {
        $this->increment('permissions_version');
        app(PermissionResolver::class)->forget($this);
    }
}
