class Listing extends Model
{
    use HasFactory, HasPrefixedId, SoftDeletes;

    protected static string $idPrefix = 'lst';

    protected $fillable = [
        'seller_id', 'category_id', 'slug', 'title', 'description', 'brand', 'model', 'condition', 'format', 'currency',
        'price_amount', 'compare_at_amount', 'minimum_offer_amount', 'negotiable', 'swappable',
        'auto_decline_below_minimum', 'stock', 'attributes', 'tags', 'aircraft_types', 'sizes', 'serial_number',
        'year_purchased', 'location', 'shipping', 'freight', 'free_delivery', 'licensing',
    ];

    protected $hidden = ['search_vector', 'serial_number'];

    protected $attributes = ['status' => 'draft', 'format' => 'physical', 'currency' => 'USD', 'stock' => 1];

    protected function casts(): array
    {
        return [
            'status' => ListingStatus::class,
            'condition' => ListingCondition::class,
            'format' => ListingFormat::class,
            'negotiable' => 'boolean',
            'swappable' => 'boolean',
            'auto_decline_below_minimum' => 'boolean',
            'free_delivery' => 'boolean',
            'attributes' => 'array',
            'tags' => 'array',
            'aircraft_types' => 'array',
            'sizes' => 'array',
            'location' => 'array',
            'shipping' => 'array',
            'freight' => 'array',
            'licensing' => 'array',
            'price_amount' => 'integer',
            'compare_at_amount' => 'integer',
            'minimum_offer_amount' => 'integer',
            'stock' => 'integer',
            'reserved_quantity' => 'integer',
            'rating_avg' => 'float',
            'promoted_until' => 'datetime',
            'reserved_until' => 'datetime',
            'moderated_at' => 'datetime',
            'submitted_at' => 'datetime',
            'published_at' => 'datetime',
        ];
    }

    // ---------------------------------------------------------------- relations

    /** @return BelongsTo<User, $this> */
    public function seller(): BelongsTo
    {
        return $this->belongsTo(User::class, 'seller_id');
    }

    /** @return BelongsTo<Category, $this> */
    public function category(): BelongsTo
    {
        return $this->belongsTo(Category::class);
    }

    /** @return MorphMany<Media, $this> */
    public function images(): MorphMany
    {
        return $this->morphMany(Media::class, 'attachable')->where('collection', 'images')->orderBy('position');
    }

    /**
     * Files delivered to buyers of digital listings (private).
     *
     * @return MorphMany<Media, $this>
     */
    public function downloads(): MorphMany
    {
        return $this->morphMany(Media::class, 'attachable')->where('collection', 'downloads')->orderBy('position');
    }

    /** @return HasMany<Offer, $this> */
    public function offers(): HasMany
    {
        return $this->hasMany(Offer::class);
    }

    /** @return HasMany<ListingPromotion, $this> */
    public function promotions(): HasMany
    {
        return $this->hasMany(ListingPromotion::class);
    }

    // ---------------------------------------------------------------- scopes

    public function scopePubliclyVisible(Builder $query): Builder
    {
        return $query->whereIn('listings.status', array_map(fn ($s) => $s->value, ListingStatus::publiclyVisible()))
            ->whereHas('seller', fn (Builder $q) => $q->whereIn('status', ['active', 'restricted']));
    }

    // ---------------------------------------------------------------- money

    public function price(): ?Money
    {
        return Money::nullable($this->price_amount, $this->currency);
    }

    public function compareAtPrice(): ?Money
    {
        return Money::nullable($this->compare_at_amount, $this->currency);
    }

    public function minimumOffer(): ?Money
    {
        return Money::nullable($this->minimum_offer_amount, $this->currency);
    }

    // ---------------------------------------------------------------- state helpers

    public function isPromoted(): bool
    {
        return $this->promoted_until !== null && $this->promoted_until->isFuture();
    }

    public function availableQuantity(): int
    {
        return max(0, $this->stock - $this->reserved_quantity);
    }

    /** Whether `$buyer` may purchase this listing right now. */
    public function isPurchasableBy(?User $buyer): bool
    {
        if ($buyer && $buyer->id === $this->seller_id) {
            return false;
        }
        if ($this->status === ListingStatus::Active) {
            return $this->availableQuantity() > 0;
        }
        if ($this->status === ListingStatus::Reserved) {
            return $buyer !== null
                && $this->reserved_for_user_id === $buyer->id
                && ($this->reserved_until === null || $this->reserved_until->isFuture())
                && $this->availableQuantity() > 0;
        }

        return false;
    }

    /** Size labels on offer, or null when the listing is not sized. */
    public function availableSizes(): ?array
    {
        $available = $this->sizes['available'] ?? null;

        return is_array($available) && $available !== [] ? $available : null;
    }

    /** Shipping option by id from the listing's options. */
    public function shippingOption(?string $id): ?array
    {
        foreach ($this->shipping ?? [] as $option) {
            if (($option['id'] ?? null) === $id) {
                return $option;
            }
        }

        return null;
    }

    public function publicPath(): string
    {
        return '/marketplace/'.$this->slug;
    }
}
