 * @property bool $swappable
 * @property bool $auto_decline_below_minimum
 * @property int $stock
 * @property int $reserved_quantity
 * @property string|null $reserved_for_user_id
 * @property Carbon|null $reserved_until
 * @property string|null $reserved_reason
