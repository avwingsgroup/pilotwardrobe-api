<?php

declare(strict_types=1);

namespace App\Models;

use App\Enums\MediaType;
use App\Support\Ids\HasPrefixedId;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\MorphTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * Cloudinary asset metadata. Public assets are served by URL; private assets
 * (`kyc`, `dispute_evidence`, `message`) use authenticated delivery and are only
 * ever exposed through short-lived signed URLs.
 */
/* @properties-start (generated by dev:model-docs) */
/**
 * @property string $id
 * @property string|null $owner_id
 * @property MediaType $type
 * @property string $visibility
 * @property string $public_id
 * @property string $resource_type
 * @property string $delivery_type
 * @property string|null $format
 * @property int|null $width
 * @property int|null $height
 * @property int|null $bytes
 * @property int|null $version
 * @property string|null $folder
 * @property string|null $secure_url
 * @property string|null $alt
 * @property string|null $placeholder
 * @property string|null $original_filename
 * @property string|null $attachable_type
 * @property string|null $attachable_id
 * @property string|null $collection
 * @property int $position
 * @property Carbon|null $attached_at
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 * @property Carbon|null $deleted_at
 */
/* @properties-end */
class Media extends Model
{
    use HasFactory, HasPrefixedId, SoftDeletes;

    protected static string $idPrefix = 'med';

    protected $table = 'media';

    protected $fillable = [
        'owner_id', 'type', 'visibility', 'public_id', 'resource_type', 'delivery_type', 'format', 'width', 'height',
        'bytes', 'version', 'folder', 'secure_url', 'alt', 'placeholder', 'original_filename', 'attachable_type',
        'attachable_id', 'collection', 'position', 'attached_at',
    ];

    protected function casts(): array
    {
        return [
            'type' => MediaType::class,
            'attached_at' => 'datetime',
            'width' => 'integer',
            'height' => 'integer',
            'bytes' => 'integer',
            'version' => 'integer',
            'position' => 'integer',
        ];
    }

    /** @return BelongsTo<User, $this> */
    public function owner(): BelongsTo
    {
        return $this->belongsTo(User::class, 'owner_id');
    }

    /** @return MorphTo<Model, $this> */
    public function attachable(): MorphTo
    {
        return $this->morphTo();
    }

    public function isPrivate(): bool
    {
        return $this->visibility === 'private';
    }

    public function isAttached(): bool
    {
        return $this->attachable_id !== null;
    }

    /** Unattached uploads owned by the user, of the given types — the only media a request may reference. */
    public function scopeAttachableBy(Builder $query, User $user, array $types): Builder
    {
        return $query->where('owner_id', $user->id)
            ->whereIn('type', array_map(fn ($t) => $t instanceof MediaType ? $t->value : $t, $types));
    }

    public function attachTo(Model $owner, string $collection, int $position = 0): void
    {
        $this->forceFill([
            'attachable_type' => $owner->getMorphClass(),
            'attachable_id' => $owner->getKey(),
            'collection' => $collection,
            'position' => $position,
            'attached_at' => now(),
        ])->save();
    }
}
